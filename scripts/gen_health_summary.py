#!/usr/bin/env python3
"""Write monthly Health summaries as Markdown. No AI, stdlib only.
Reads health/data/*.csv (read-only); writes memory/health/YYYY-MM.md and index.md.
Aggregates only; free-text notes are not copied."""
import csv, sys
from collections import defaultdict
from pathlib import Path

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else "/home/beedme/data/workspace/health/data")
OUT = Path(sys.argv[2] if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "memory" / "health")

def num(v):
    try: return float(v)
    except (TypeError, ValueError): return None

def load(name):
    p = SRC / f"{name}.csv"
    if not p.exists(): return defaultdict(list)
    d = defaultdict(list)
    with p.open(newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r.get("date"): d[r["date"][:7]].append(r)
    return d

weight, nutri, work, jabs, side = (load(n) for n in ("weight", "nutrition", "workouts", "jabs", "side_effects"))
months = sorted(set(weight) | set(nutri) | set(work) | set(jabs) | set(side))

def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + \
           ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]

def avg(xs): return f"{sum(xs)/len(xs):.1f}" if xs else "-"

OUT.mkdir(parents=True, exist_ok=True)
for m in months:
    L = [f"# Health summary {m}", "",
         "Generated from the Health app data by `scripts/gen_health_summary.py` (no AI). Raw measurements stay in the Health app. Not medical advice.", ""]
    w = sorted((r for r in weight.get(m, []) if (r.get("deleted") or "").lower() not in ("1", "true") and num(r.get("weight_kg")) is not None), key=lambda r: r["date"])
    L += ["## Weight", ""]
    if w:
        v = [num(r["weight_kg"]) for r in w]
        L += table(["Measurements", "First", "Last", "Change", "Min", "Max", "Average"],
                   [(len(v), f"{v[0]:.1f} ({w[0]['date']})", f"{v[-1]:.1f} ({w[-1]['date']})", f"{v[-1]-v[0]:+.1f}", f"{min(v):.1f}", f"{max(v):.1f}", avg(v))])
        L.append("\nValues in kg.")
    else: L.append("No measurements.")
    n = nutri.get(m, [])
    L += ["", "## Nutrition", ""]
    if n:
        days = defaultdict(lambda: [0.0, 0.0, 0.0, 0.0])
        for r in n:
            for i, k in enumerate(("kcal", "protein_g", "carbs_g", "fat_g")):
                days[r["date"]][i] += num(r.get(k)) or 0
        t = list(days.values())
        L += table(["Days logged", "Avg kcal/day", "Avg protein g/day", "Avg carbs g/day", "Avg fat g/day"],
                   [(len(t), *(avg([d[i] for d in t]) for i in range(4)))])
    else: L.append("No meals logged.")
    wk = work.get(m, [])
    L += ["", "## Training", ""]
    if wk:
        sess = defaultdict(set)
        for r in wk: sess[r.get("session") or "-"].add(r["date"])
        L += [f"- Training days: {len({r['date'] for r in wk})}", f"- Exercise rows: {len(wk)}"]; L.append("")
        L += table(["Session", "Days"], [(k, len(v)) for k, v in sorted(sess.items())])
    else: L.append("No workouts.")
    j = sorted(jabs.get(m, []), key=lambda r: r["date"])
    L += ["", "## Jab (tirzepatide)", ""]
    L += table(["Date", "Dose mg", "Site"], [(r["date"], r.get("dose_mg", ""), r.get("injection_site", "")) for r in j]) if j else ["No injections."]
    s = side.get(m, [])
    L += ["", "## Side effects", ""]
    if s:
        c = defaultdict(int)
        for r in s: c[r.get("symptom_type") or "-"] += 1
        L += table(["Symptom", "Entries"], sorted(c.items()))
    else: L.append("None logged.")
    (OUT / f"{m}.md").write_text("\n".join(L) + "\n", encoding="utf-8")

idx = ["# Health summaries", "", "Monthly summaries generated by `scripts/gen_health_summary.py`.", ""]
idx += [f"- [{m}]({m}.md)" for m in reversed(months)]
(OUT / "index.md").write_text("\n".join(idx) + "\n", encoding="utf-8")
print(f"health: {len(months)} months written to {OUT}")
