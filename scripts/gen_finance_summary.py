#!/usr/bin/env python3
"""Write monthly Finance summaries as Markdown. No AI, stdlib only.
Reads personal-finance/data/transactions.csv (read-only); writes memory/finance/YYYY-MM.md
and memory/finance/index.md. Aggregates only: no single transactions are copied."""
import csv, sys
from collections import defaultdict
from pathlib import Path

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else "/home/beedme/data/workspace/personal-finance/data/transactions.csv")
OUT = Path(sys.argv[2] if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "memory" / "finance")
TOP = 8

def num(v):
    try: return float(v)
    except (TypeError, ValueError): return 0.0

months = defaultdict(list)
with SRC.open(newline="", encoding="utf-8") as f:
    for r in csv.DictReader(f):
        if r.get("date"): months[r["date"][:7]].append(r)

def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out

OUT.mkdir(parents=True, exist_ok=True)
for m, rows in sorted(months.items()):
    cur = defaultdict(lambda: {"in": 0.0, "out": 0.0, "n": 0})
    cat = defaultdict(float); mer = defaultdict(float); acc = defaultdict(int)
    review = 0
    for r in rows:
        c = r.get("currency", "?"); a = num(r.get("amount"))
        cur[c]["n"] += 1
        cur[c]["in" if a > 0 else "out"] += a
        acc[r.get("account", "?")] += 1
        if a < 0:
            cat[(c, r.get("spending_type") or "-")] += -a
            mer[(c, r.get("merchant") or r.get("merchant_raw") or "-")] += -a
        if (r.get("needs_review") or "").lower() == "true": review += 1
    L = [f"# Finance summary {m}", "",
         "Generated from the Finance app data by `scripts/gen_finance_summary.py` (no AI). Amounts are in the original currency, not converted. Raw transactions stay in the Finance app.", "",
         f"- Transactions: {len(rows)}", f"- Needing review: {review}",
         "- Accounts: " + ", ".join(f"{k} ({v})" for k, v in sorted(acc.items())), "",
         "## Totals by currency", ""]
    L += table(["Currency", "Transactions", "Money in", "Money out", "Net"],
               [(c, d["n"], f"{d['in']:.2f}", f"{d['out']:.2f}", f"{d['in']+d['out']:.2f}") for c, d in sorted(cur.items())])
    L += ["", "## Spending by category", ""]
    L += table(["Currency", "Category", "Spent"],
               [(c, k, f"{v:.2f}") for (c, k), v in sorted(cat.items(), key=lambda x: (x[0][0], -x[1]))])
    L += ["", f"## Top {TOP} merchants by spending", ""]
    top = []
    for c in sorted({k[0] for k in mer}):
        top += sorted(((c, k[1], v) for k, v in mer.items() if k[0] == c), key=lambda x: -x[2])[:TOP]
    L += table(["Currency", "Merchant", "Spent"], [(c, k, f"{v:.2f}") for c, k, v in top])
    (OUT / f"{m}.md").write_text("\n".join(L) + "\n", encoding="utf-8")

idx = ["# Finance summaries", "", "Monthly summaries generated by `scripts/gen_finance_summary.py`.", ""]
idx += [f"- [{m}]({m}.md): {len(r)} transactions" for m, r in sorted(months.items(), reverse=True)]
(OUT / "index.md").write_text("\n".join(idx) + "\n", encoding="utf-8")
print(f"finance: {len(months)} months written to {OUT}")
